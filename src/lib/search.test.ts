import { afterEach, expect, it, vi } from "vitest";
import { annotateRnaEvidence, searchRequest } from "./search";

afterEach(() => vi.unstubAllGlobals());

it("routes gene searches to the fixed EBI Search domain with bounded paging", async () => {
  const fetch = vi.fn().mockResolvedValue(Response.json({ hitCount: 1, entries: [] }));
  vi.stubGlobal("fetch", fetch);
  await searchRequest({ method: "GET", path: "/search/", params: { query: 'entry_type:Gene AND NCBI_TAXONOMY_ID:9606', fields: "id,gene_member" } });
  const url = new URL(String(fetch.mock.calls[0][0]));
  expect(url.origin + url.pathname).toBe("https://www.ebi.ac.uk/ebisearch/ws/rest/rnacentral");
  expect(Object.fromEntries(url.searchParams)).toEqual({ query: 'entry_type:Gene AND NCBI_TAXONOMY_ID:9606', fields: "id,gene_member", size: "10", start: "0", format: "json" });
});

it("discovers provider field capabilities and release information", async () => {
  const fetch = vi.fn().mockResolvedValue(Response.json({ domains: [] }));
  vi.stubGlobal("fetch", fetch);
  await searchRequest({ method: "GET", path: "/search/fields/" });
  expect(String(fetch.mock.calls[0][0])).toBe("https://www.ebi.ac.uk/ebisearch/ws/rest/rnacentral?format=json");
});

it.each([
  { path: "/search/other" }, { path: "/search" },
  { path: "/search/fields", params: { query: "*" } },
  { path: "/search", params: { query: "*", url: "https://example.org" } },
  { path: "/search", params: { query: "*", size: 101 } },
  { path: "/search", params: { query: "*", size: 0 } },
  { path: "/search", params: { query: "*", size: "10" } },
  { path: "/search", params: { query: "*", start: -1 } },
])("rejects malformed discovery/paging requests before fetching: %j", input => {
  const fetch = vi.fn(); vi.stubGlobal("fetch", fetch);
  expect(() => searchRequest({ method: "GET", ...input })).toThrow();
  expect(fetch).not.toHaveBeenCalled();
});

it("labels generated summaries without modifying warnings, primary IDs or citations", () => {
  const data = { summary: "WARNING: This summary was generated by AI. [PMC6721825]", primary_id: "URS00005C2E31_10090" };
  expect(annotateRnaEvidence("/litsumm/mmu-mir-191/", data)).toMatchObject({ ...data, meta: { rnacentral: { experimental_evidence: false } } });
  expect(annotateRnaEvidence("/litsumm/", { results: [data], next: "page2" })).toMatchObject({ results: [data], next: "page2" });
});

it("keeps predicted gene identities distinct from curated genes and incomplete search lists", () => {
  const genes = { count: 1, results: [{ gene_name: "RNACG48157878589.2" }] };
  expect(annotateRnaEvidence("/rna/URS0000D59DC9/genes/9606/", genes)).toMatchObject({ ...genes, meta: { rnacentral: { evidence_type: "predicted gene grouping" } } });
  expect(annotateRnaEvidence("/search/", { hitCount: 1 })).toHaveProperty("meta.rnacentral.guidance", expect.stringContaining("truncated"));
  expect(annotateRnaEvidence("/rna/", genes)).toBe(genes);
  expect(() => annotateRnaEvidence("/litsumm/", [])).toThrow("JSON object");
});

it.each([{ release: "27", rnacentral: "provider value", upstream: ["native"] }, null, "source metadata", [1, 2]])("preserves native meta without confusing it with local evidence labels: %j", meta => {
  const native = { hitCount: 1, entries: [{ id: "RNACG48157878589.2" }], meta };
  expect(annotateRnaEvidence("/search/", native)).toMatchObject({
    hitCount: 1, entries: native.entries, meta: { upstream: meta, rnacentral: { evidence_type: "EBI Search index" } },
  });
  expect(native.meta).toBe(meta);
});
